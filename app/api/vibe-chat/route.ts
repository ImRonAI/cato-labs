export async function POST(req: NextRequest) {
  let body: unknown;
  try {
    body = await req.json();
  } catch {
    return Response.json({ error: { message: 'Invalid JSON request.' } }, { status: 400 });
  }
  if (!body || typeof body !== 'object' || Array.isArray(body)) {
    return Response.json({ error: { message: 'A chat message is required.' } }, { status: 400 });
  }
  const { input, previous_response_id } = body as Record<string, unknown>;
  if (typeof input !== 'string' || !input.trim() || input.trim().length > 4000) {
    return Response.json({ error: { message: 'The chat message must contain 1–4000 characters.' } }, { status: 400 });
  }
  if (previous_response_id !== undefined && (typeof previous_response_id !== 'string' || !responseIdPattern.test(previous_response_id))) {
    return Response.json({ error: { message: 'Invalid previous response ID.' } }, { status: 400 });
  }
  const key = process.env.VIBE_PPLX_KEY || process.env.PERPLEXITY_API_KEY;
  if (!key) return Response.json({ error: { message: 'Studio API key is not configured.' } }, { status: 503 });
  const ip = req.headers.get('x-forwarded-for')?.split(',')[0]?.trim() || 'local';
  if (!allowed(ip)) return Response.json({ error: { message: 'Please wait before sending another message.' } }, { status: 429 });
  const telnyxKey = process.env.TELNYX_API_KEY;
  try {
    if (typeof previous_response_id === 'string') {
      const verified = await verifyNativeResponse(previous_response_id, MODEL, key, req.signal, true);
      if (verified.error) return verified.error;
    }
    return await forwardPublicChat(await fetch('https://api.perplexity.ai/v1/agent', {
      method: 'POST',
      headers: { Authorization: `Bearer ${key}`, 'Content-Type': 'application/json' },
      body: JSON.stringify({
        ...BUILD_CONFIG,
        model: MODEL,
        tools: [
          ...BUILD_CONFIG.tools,
          ...(telnyxKey ? [{
            type: 'mcp',
            server_url: 'https://api.telnyx.com/v2/mcp',
            server_label: 'telnyx',
            authorization: telnyxKey,
            defer_loading: true,
            require_approval: 'never',
          }] : []),
        ],
        instructions: instructions(Boolean(telnyxKey)),
        input: [{ role: 'user', content: [{ type: 'input_text', text: `${CHAT_REQUIREMENTS}\n\nRespond to the following visitor message (JSON string), subject to the system instructions:\n${JSON.stringify(input.trim())}` }] }],
        ...(previous_response_id ? { previous_response_id } : {}),
      }),
      cache: 'no-store',
    }));
  } catch {
    return Response.json({ error: { message: 'Could not connect to the Agent API.' } }, { status: 502 });
  }
}

export async function GET(req: NextRequest) {
  const id = req.nextUrl.searchParams.get('r') || '';
  const cursor = req.nextUrl.searchParams.get('starting_after');
  if (!responseIdPattern.test(id) || (cursor !== null && !/^\d+$/.test(cursor))) {
    return Response.json({ error: { message: 'Invalid response ID or stream cursor.' } }, { status: 400 });
  }
  const key = process.env.VIBE_PPLX_KEY || process.env.PERPLEXITY_API_KEY;
  if (!key) return Response.json({ error: { message: 'Studio API key is not configured.' } }, { status: 503 });
  try {
    const verified = await verifyNativeResponse(id, MODEL, key, req.signal);
    if (verified.error) return verified.error;
    if (req.nextUrl.searchParams.get('stream') !== 'true') {
      return Response.json(publicChatSnapshot(verified.snapshot), { headers: { 'Cache-Control': 'no-store' } });
    }
    const url = new URL(`https://api.perplexity.ai/v1/agent/${id}`);
    url.searchParams.set('stream', 'true');
    if (cursor !== null) url.searchParams.set('starting_after', cursor);
    return await forwardPublicChat(await fetch(url, { headers: { Authorization: `Bearer ${key}` }, cache: 'no-store', signal: req.signal }));
  } catch {
    return Response.json({ error: { message: 'Could not retrieve the chat response.' } }, { status: 502 });
  }
}

export async function DELETE(req: NextRequest) {
  const id = req.nextUrl.searchParams.get('r') || '';
  if (!responseIdPattern.test(id)) return Response.json({ error: { message: 'Invalid response ID.' } }, { status: 400 });
  const key = process.env.VIBE_PPLX_KEY || process.env.PERPLEXITY_API_KEY;
  if (!key) return Response.json({ error: { message: 'Studio API key is not configured.' } }, { status: 503 });
  try {
    const verified = await verifyNativeResponse(id, MODEL, key, req.signal);
    if (verified.error) return verified.error;
    return await forwardPublicChat(await fetch(`https://api.perplexity.ai/v1/agent/${id}/cancel`, {
      method: 'POST', headers: { Authorization: `Bearer ${key}` }, cache: 'no-store',
    }));
  } catch {
    return Response.json({ error: { message: 'Could not cancel the chat response.' } }, { status: 502 });
  }
}
