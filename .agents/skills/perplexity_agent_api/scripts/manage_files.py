#!/usr/bin/env python3
"""
CLI tool to inspect and download sandbox-generated files from Perplexity Agent responses.
Endpoints:
- GET /v1/agent/{id}/files
- GET /v1/agent/{id}/files/{file_id}/content
"""

import os
import sys
import json
import argparse
from perplexity_client import PerplexityAgentClient


def main():
    parser = argparse.ArgumentParser(description="Manage files produced by Perplexity Agent responses.")
    parser.add_argument("--api-key", type=str, default=None, help="Explicit API key.")
    subparsers = parser.add_subparsers(dest="command", required=True)

    # list
    list_p = subparsers.add_parser("list", help="List files for a response ID.")
    list_p.add_argument("response_id", type=str, help="Response ID.")
    list_p.add_argument("--json", action="store_true", help="Output raw JSON.")

    # download
    dl_p = subparsers.add_parser("download", help="Download a specific file or all files.")
    dl_p.add_argument("response_id", type=str, help="Response ID.")
    dl_p.add_argument("--file-id", type=str, default=None, help="Specific file ID to download.")
    dl_p.add_argument("--out", type=str, required=True, help="Destination directory or file path.")

    args = parser.parse_args()
    client = PerplexityAgentClient(api_key=args.api_key)

    try:
        if args.command == "list":
            files = client.list_response_files(args.response_id)
            if args.json:
                print(json.dumps(files, indent=2))
                return
            if not files:
                print(f"No files found for response {args.response_id}.")
                return
            print(f"\nFiles generated by response {args.response_id} ({len(files)} found):\n")
            print(f"{'File ID':<36} {'Filename':<30} {'Size (Bytes)'}")
            print("-" * 80)
            for f in files:
                fid = f.get("id", "")
                fname = f.get("filename", "")
                size = str(f.get("size_bytes", f.get("size", "")))
                print(f"{fid:<36} {fname:<30} {size}")

        elif args.command == "download":
            if args.file_id:
                dest = args.out
                if os.path.isdir(dest):
                    # fetch filename from list
                    files = client.list_response_files(args.response_id)
                    matched = next((f for f in files if f.get("id") == args.file_id), None)
                    fname = matched.get("filename") if matched else f"file_{args.file_id}"
                    dest = os.path.join(dest, fname)
                path = client.download_response_file(args.response_id, args.file_id, dest)
                print(f"[+] Downloaded file to: {path}")
            else:
                paths = client.download_all_response_files(args.response_id, args.out)
                print(f"[+] Downloaded {len(paths)} file(s) to: {args.out}")
                for p in paths:
                    print(f"  - {p}")

    except Exception as e:
        sys.stderr.write(f"Error: {e}\n")
        sys.exit(1)


if __name__ == "__main__":
    main()
